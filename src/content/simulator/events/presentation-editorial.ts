export function editorialPresentation(definition:EventDefinitionV1, variation:EventVariation):NonNullable<EventVariation['presentation']>{
 const bullets=situationDetails[definition.id]??details[definition.familyId];
 if(!bullets)throw new Error(`Missing curated situation details: ${definition.id}`);
 const contextualCosts:Record<string,{index:number;text:string}>={
   weekend_local_trip:{index:1,text:'Contribuția la transport'},social_group_bowling:{index:1,text:'Partea ta din costul pistei'},
   digital_cable_fault:{index:1,text:'Un cablu nou'},school_project_cardboard:{index:0,text:'Material pentru machetă'},
 };
 const cost=contextualCosts[definition.id];
 return { title:displayTitles[definition.id]??variation.title, context:contexts[definition.id]??variation.description,
   bullets:bullets.map((text,i)=>cost?.index===i?{text:cost.text,costOptionId:variation.options[0].id}:{text}) };
}
